/**
 * RecommendationPromptBuilder - 本日のおすすめ商品を調査するためのプロンプトを構築
 */

export class RecommendationPromptBuilder {
  private readonly today: string;

  constructor() {
    // JSTで現在の日付を取得 (YYYY-MM-DD)
    this.today = new Date()
      .toLocaleDateString('ja-JP', {
        timeZone: 'Asia/Tokyo',
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
      })
      .replaceAll('/', '-');
  }

  public build(): string {
    return `【ミッション：本日（${this.today}）の「本当に今買うべき」おすすめ商品調査】
あなたは優秀なAIエージェントとして、Amazon商品の調査・選定を行います。
単に「季節に合っているから」というありきたりな理由ではなく、ユーザーが「毎日更新されるこの情報を見る価値がある」「確かに今日買うべきだ」と納得できる、鮮度と説得力のある商品セレクションを作成してください。

---

## 調査の進め方
1. **本日のコンテキスト（動機付け）の分析**:
   - まず、本日の日付（${this.today}）における最新のトレンド、急上昇ワード、時事ニュース、急な天候変化、あるいはAmazon内での特選タイムセール情報などを考慮・検索してください。
   - 「今日、人々は何を欲しがっているか？」「今日買うことでどんな得があるか？」という視点を持ってください。
2. **探索テーマとキーワードの策定**:
   - 上記の分析に基づき、「本当に今買うべき理由」があるテーマを設定します。
   - 【良い例】：「昨日話題になった〇〇に関連する商品」「急激な冷え込みに対応する即納防寒グッズ」「本日〇〇%OFFの特選タイムセール品」
   - 【悪い例】：「春だから新生活グッズ」「冬だから暖房器具」（※具体性と本日の必然性がない）
   - 設定したテーマをもとに、検索キーワードとSearch Indexを決定してください。
3. **商品検索と一次選定**:
   - \`python scripts/creators_search_items.py "キーワード" --search-index Index名\` を実行して候補をリストアップします。
   - 検索結果から、評価の高さだけでなく、価格の変動（割引されているか）、在庫状況などを考慮して候補を絞り込みます。
4. **詳細調査と「今買うべき」確証の取得**:
   - 候補商品のASINを用いて \`python scripts/creators_get_item.py ASIN\` を実行し、詳細なスペック、特徴、価格情報を取得します。
   - 価格競争力、最新の機能、ユーザーの現在の痛みをどう解決するかなど、推奨に足る確たる証拠を集め、合計3〜5点の最高の商品を厳選してください。
5. **推奨理由と「今日である理由」の言語化**:
   - なぜ「明日」でも「昨日」でもなく「今日」おすすめするのかを明確に言語化してください。

---

## 成果物の作成と検証
- 調査結果を \`data/recommendations/today.json\` に保存してください。
- ファイル作成後、\`python scripts/validate_artifact.py\` (利用可能な場合) でチェックしてください。
- **注意**: ハルシネーション（存在しない商品情報やURL、架空のセール情報の創作）は厳禁です。必ず取得した事実に基づいてください。

---

## 出力形式 (JSON)
\`data/recommendations/today.json\` の構造：
\`\`\`json
{
  "date": "${this.today}",
  "headline": "本日の注目商品セレクション：[テーマ名]",
  "recommendations": [
    {
      "asin": "ASIN",
      "title": "商品名",
      "price": "価格",
      "category": "カテゴリ",
      "reason": "この商品自体が優れている理由（スペックやコスパなど）",
      "whyBuyNow": "なぜ『今日』買うべきなのか（例：本日限定セール中、昨日発表の〇〇に対応、急な気温変化のため等）",
      "highlights": ["特徴1", "特徴2"],
      "url": "https://www.amazon.co.jp/dp/ASIN/",
      "imageUrl": "画像のURL (存在する場合)"
    }
  ],
  "searchContext": {
    "themes": ["選定した具体的なテーマ1", "テーマ2"],
    "todayContext": "本日の選定基準となった背景情報（トレンドや天候、セール状況など）",
    "keywords": ["使用したキーワード1", "キーワード2"]
  }
}
\`\`\`

それでは、本日の情報収集から調査を開始してください。`;
  }
}
